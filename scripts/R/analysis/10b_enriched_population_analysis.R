# ===============================================================================
# Calculates ICERs for a "ceiling scenario" where only biomarker-positive
# patients are considered. For each biomarker strategy:
#   - Experimental arm: biomarker-positive patients on FLOX + nivolumab
#   - Control arm: biomarker-positive patients on FLOX only
#
# This is an apples-to-apples comparison within the enriched (biomarker+) cohort,
# as in a biomarker-enriched trial design where only positive patients are enrolled.
#
# Biomarker-positive experimental curves already exist in l_params_base.
# Biomarker-positive control curves are generated by predicting from the fitted
# survival models for positive patients assigned to the control treatment.
#
# Runs across all three model structures (A=joint, B=focused, C=separate)
# and compares enriched ICERs to base case ICERs.
#
# Prerequisites:
#   - 02_setup_and_global_variables.R (global vars)
#   - 03_biomarker_strategies.R (biomarker definitions)
#   - 06/07 are re-sourced automatically by run_basecase_for_structure()
# ===============================================================================

