#' Format enriched vs base case comparison table
#'
#' @param all_results Named list from run_all_enriched_analyses()
#' @return Data frame with comparison metrics
format_enriched_comparison_table <- function(all_results) {

  model_configs <- get_model_configs()
  biomarkers <- c("crp", "tlr", "tmb_braf")
  biomarker_labels <- c("CRP", "TLR", "TMB/BRAF")

  rows <- list()

  for (i in seq_along(biomarkers)) {
    bm <- biomarkers[i]
    row <- data.frame(Biomarker = biomarker_labels[i], stringsAsFactors = FALSE)

    for (model_name in names(all_results)) {
      result <- all_results[[model_name]]
      sl <- model_configs[[model_name]]$short_label

      base_row <- result$base_pairwise[result$base_pairwise$Strategy == bm, ]
      enriched_row <- result$enriched_pairwise[result$enriched_pairwise$Strategy == bm, ]

      # Base case metrics (vs overall control)
      row[[paste0("Base_Cost_", sl)]] <- base_row$Cost
      row[[paste0("Base_Effect_", sl)]] <- base_row$Effect
      row[[paste0("Base_ICER_", sl)]] <- base_row$ICER
      row[[paste0("Base_Status_", sl)]] <- base_row$Status

      # Enriched metrics (vs biomarker+ control)
      row[[paste0("Enr_Cost_", sl)]] <- enriched_row$Cost
      row[[paste0("Enr_Effect_", sl)]] <- enriched_row$Effect
      row[[paste0("Enr_Ctrl_Cost_", sl)]] <- enriched_row$Ctrl_Cost
      row[[paste0("Enr_Ctrl_Effect_", sl)]] <- enriched_row$Ctrl_Effect
      row[[paste0("Enr_ICER_", sl)]] <- enriched_row$ICER
      row[[paste0("Enr_Status_", sl)]] <- enriched_row$Status

      # Percentage change in ICER (only meaningful when both are non-dominated)
      base_icer <- base_row$ICER
      enr_icer <- enriched_row$ICER
      base_status <- base_row$Status
      enr_status <- enriched_row$Status
      if (base_status == "Non-dominated" && enr_status == "Non-dominated" &&
          !is.na(base_icer) && !is.na(enr_icer) &&
          base_icer != 0 && is.finite(base_icer) && is.finite(enr_icer)) {
        row[[paste0("Pct_Change_", sl)]] <- (enr_icer - base_icer) / abs(base_icer) * 100
      } else {
        row[[paste0("Pct_Change_", sl)]] <- NA_real_
      }
    }

    rows[[i]] <- row
  }

  comparison_df <- do.call(rbind, rows)

  # Add prevalence column
  if (exists("strategies_df")) {
    comparison_df$Prevalence <- sapply(biomarkers, function(bm) {
      strategies_df$prevalence[strategies_df$id == bm]
    })
  } else {
    comparison_df$Prevalence <- NA_real_
  }

  col_order <- c("Biomarker", "Prevalence",
                 setdiff(names(comparison_df), c("Biomarker", "Prevalence")))
  comparison_df <- comparison_df[, col_order]

  return(comparison_df)
}

#' Format enriched comparison table for display
#'
#' @param comparison_df Data frame from format_enriched_comparison_table()
#' @return Formatted data frame suitable for printing or kable
format_enriched_for_display <- function(comparison_df) {

  display_df <- comparison_df

  # Format prevalence
  display_df$Prevalence <- sprintf("%.1f%%", display_df$Prevalence * 100)

  # Format cost columns
  cost_cols <- grep("^(Base_Cost_|Enr_Cost_|Enr_Ctrl_Cost_)", names(display_df), value = TRUE)
  for (col in cost_cols) {
    display_df[[col]] <- scales::dollar(display_df[[col]], prefix = "EUR ", accuracy = 1)
  }

  # Format effect columns
  effect_cols <- grep("^(Base_Effect_|Enr_Effect_|Enr_Ctrl_Effect_)", names(display_df), value = TRUE)
  for (col in effect_cols) {
    display_df[[col]] <- sprintf("%.3f", display_df[[col]])
  }

  # Format ICER columns with status handling
  icer_cols <- grep("^(Base_ICER_|Enr_ICER_)", names(display_df), value = TRUE)
  for (icer_col in icer_cols) {
    status_col <- gsub("ICER", "Status", icer_col)
    if (status_col %in% names(display_df)) {
      display_df[[icer_col]] <- ifelse(
        display_df[[status_col]] == "Dominated",
        "Dominated",
        ifelse(display_df[[status_col]] == "Reference",
               "--",
               ifelse(is.na(display_df[[icer_col]]) | !is.finite(as.numeric(display_df[[icer_col]])),
                      "--",
                      scales::dollar(as.numeric(display_df[[icer_col]]), prefix = "EUR ", accuracy = 1)))
      )
    }
  }

  # Format percentage change columns
  pct_cols <- grep("^Pct_Change_", names(display_df), value = TRUE)
  for (col in pct_cols) {
    display_df[[col]] <- ifelse(
      is.na(display_df[[col]]),
      "--",
      sprintf("%+.1f%%", as.numeric(display_df[[col]]))
    )
  }

  # Remove status columns from display
  display_df <- display_df[, !grepl("^(Base_Status_|Enr_Status_)", names(display_df))]

  return(display_df)
}

