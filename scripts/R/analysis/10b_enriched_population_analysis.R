#' Calculate simple pairwise ICERs (each strategy vs control)
#'
#' @param results Data frame with Strategy, Cost, Effect columns (from model_fun)
#' @return Data frame with columns: Strategy, Cost, Effect, Inc_Cost, Inc_Effect, ICER, Status
calculate_pairwise_icers <- function(results) {
  control_cost <- results$Cost[results$Strategy == "control"]
  control_effect <- results$Effect[results$Strategy == "control"]

  pairwise_df <- data.frame(
    Strategy = results$Strategy,
    Cost = results$Cost,
    Effect = results$Effect,
    Inc_Cost = results$Cost - control_cost,
    Inc_Effect = results$Effect - control_effect,
    stringsAsFactors = FALSE
  )

  pairwise_df$ICER <- ifelse(
    pairwise_df$Strategy == "control",
    NA_real_,
    pairwise_df$Inc_Cost / pairwise_df$Inc_Effect
  )

  pairwise_df$Status <- ifelse(
    pairwise_df$Strategy == "control",
    "Reference",
    ifelse(pairwise_df$Inc_Cost > 0 & pairwise_df$Inc_Effect <= 0,
           "Dominated",
           ifelse(pairwise_df$Inc_Cost < 0 & pairwise_df$Inc_Effect > 0,
                  "Cost-saving",
                  "Non-dominated"))
  )

  return(pairwise_df)
}

#' Generate survival curves for biomarker-positive patients on control treatment
#'
#' Uses the fitted survival models (available in global env after run_basecase_for_structure)
#' to predict OS and PFS for biomarker-positive patients assigned to control Rx.
#'
#' @param biomarker_name Character: "crp", "tlr", or "tmb_braf"
#' @return List with $os and $pfs vectors (population-averaged survival curves)
generate_enriched_control_curves <- function(biomarker_name) {

  # data_complete, models, time_points are in global env from script 06
  ctrl_rx <- levels(data_complete$Rx)[1]

  # Filter to biomarker-positive patients
  pos_data <- data_complete[as.numeric(as.character(data_complete[[biomarker_name]])) == 1, ]
  pos_data$Rx <- factor(ctrl_rx, levels = levels(data_complete$Rx))

  # Get the appropriate fitted model
  if (uses_per_strategy_formulas()) {
    # Models B/C: biomarker-specific model
    model_os <- models$best_fit[[biomarker_name]]$os
    model_pfs <- models$best_fit[[biomarker_name]]$pfs
  } else {
    # Model A: shared model
    model_os <- models$best_fit$os
    model_pfs <- models$best_fit$pfs
  }

  # Predict survival for biomarker-positive patients on control
  os_pred <- predict(model_os, newdata = pos_data, type = "survival", times = time_points)
  pfs_pred <- predict(model_pfs, newdata = pos_data, type = "survival", times = time_points)

  # Extract and population-average
  os_matrix <- extract_all_survival_probabilities(os_pred)
  pfs_matrix <- extract_all_survival_probabilities(pfs_pred)

  list(
    os = rowMeans(os_matrix, na.rm = TRUE),
    pfs = rowMeans(pfs_matrix, na.rm = TRUE)
  )
}

#' Compute state occupancy from survival curves with constraints
#'
#' @param os OS survival vector
#' @param pfs PFS survival vector
#' @param label Label for warning messages
#' @return List with p_pf, p_p, p_d vectors
compute_state_occupancy <- function(os, pfs, label = "") {
  # Enforce PFS <= OS
  pfs <- pmin(pfs, os)

  p_pf <- pfs
  p_p <- pmax(os - pfs, 0)
  p_d <- 1 - os

  # Force initial state: 100% progression-free
  p_pf[1] <- 1.0
  p_p[1] <- 0.0
  p_d[1] <- 0.0

  list(p_pf = p_pf, p_p = p_p, p_d = p_d)
}

#' Run enriched population analysis for a specific model structure
#'
#' For each biomarker, computes:
#'   - Enriched experimental: biomarker+ patients on experimental treatment
#'   - Enriched control: biomarker+ patients on standard treatment (new curves)
#'   - Enriched ICER: (exp_cost - ctrl_cost) / (exp_effect - ctrl_effect)
#'
#' @param model_structure Integer (0, 1, or 2)
#' @param verbose Logical, print progress messages
#' @return List with base and enriched results
run_enriched_for_structure <- function(model_structure, verbose = TRUE) {

  # Run base case (re-sources 06+07, populates global env)
  base_result <- run_basecase_for_structure(model_structure, verbose = verbose)
  base_pairwise <- calculate_pairwise_icers(base_result$base_results)

  if (verbose) {
    cat("  Generating enriched population curves (biomarker+ control)...\n")
  }

  # Discount factors
  v_dw_c <- 1 / (1 + l_params_base$dr_costs)^(seq(0, time_horizon) / 52)
  v_dw_e <- 1 / (1 + l_params_base$dr_effects)^(seq(0, time_horizon) / 52)

  biomarkers <- get_biomarkers()
  enriched_rows <- list()

  for (biomarker in biomarkers) {

    # --- Enriched experimental arm (existing curves) ---
    os_exp <- l_params_base$p_os[[paste0(biomarker, "_pos_OS")]]
    pfs_exp <- l_params_base$p_pfs[[paste0(biomarker, "_pos_PFS")]]
    states_exp <- compute_state_occupancy(os_exp, pfs_exp, paste0(biomarker, "+ exp"))

    exp_outcomes <- calculate_outcomes(
      params = l_params_base,
      p_pf = states_exp$p_pf,
      p_p = states_exp$p_p,
      p_d = states_exp$p_d,
      treatment_type = "experimental",
      biomarker = biomarker,
      v_dw_c = v_dw_c,
      v_dw_e = v_dw_e,
      cl = cl
    )

    # --- Enriched control arm (new curves: biomarker+ on FLOX) ---
    ctrl_curves <- generate_enriched_control_curves(biomarker)
    states_ctrl <- compute_state_occupancy(ctrl_curves$os, ctrl_curves$pfs,
                                           paste0(biomarker, "+ ctrl"))

    ctrl_outcomes <- calculate_outcomes(
      params = l_params_base,
      p_pf = states_ctrl$p_pf,
      p_p = states_ctrl$p_p,
      p_d = states_ctrl$p_d,
      treatment_type = "standard",
      biomarker = biomarker,
      v_dw_c = v_dw_c,
      v_dw_e = v_dw_e,
      cl = cl
    )

    # --- Compute enriched ICER ---
    inc_cost <- exp_outcomes$costs_total - ctrl_outcomes$costs_total
    inc_effect <- exp_outcomes$qalys_total - ctrl_outcomes$qalys_total

    if (inc_cost > 0 & inc_effect <= 0) {
      status <- "Dominated"
    } else if (inc_cost < 0 & inc_effect > 0) {
      status <- "Cost-saving"
    } else {
      status <- "Non-dominated"
    }

    icer_val <- inc_cost / inc_effect

    enriched_rows[[biomarker]] <- data.frame(
      Strategy = biomarker,
      Cost = exp_outcomes$costs_total,
      Effect = exp_outcomes$qalys_total,
      Ctrl_Cost = ctrl_outcomes$costs_total,
      Ctrl_Effect = ctrl_outcomes$qalys_total,
      Inc_Cost = inc_cost,
      Inc_Effect = inc_effect,
      ICER = icer_val,
      Status = status,
      stringsAsFactors = FALSE
    )
  }

  enriched_pairwise <- do.call(rbind, enriched_rows)
  rownames(enriched_pairwise) <- NULL

  if (verbose) {
    cat("  Enriched analysis complete.\n")
  }

  return(list(
    base_results = base_result$base_results,
    base_pairwise = base_pairwise,
    base_icer_obj = base_result$icer_obj,
    enriched_pairwise = enriched_pairwise,
    model_structure = model_structure
  ))
}

#' Run enriched population analysis for all model structures
#'
#' @param verbose Logical, print progress messages
#' @return Named list of results for each model structure
run_all_enriched_analyses <- function(verbose = TRUE) {

  model_configs <- get_model_configs()
  all_results <- list()

  for (model_name in names(model_configs)) {
    config <- model_configs[[model_name]]

    if (verbose) {
      cat("\n", rep("=", 70), "\n", sep = "")
      cat("ENRICHED ANALYSIS:", config$label, "\n")
      cat(rep("=", 70), "\n", sep = "")
    }

    all_results[[model_name]] <- run_enriched_for_structure(
      model_structure = config$structure,
      verbose = verbose
    )
    all_results[[model_name]]$config <- config
  }

  return(all_results)
}

