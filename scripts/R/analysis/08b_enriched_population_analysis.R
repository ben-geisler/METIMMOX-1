# ===============================================================================

cat("\n")
cat(rep("=", 80), "\n", sep = "")
cat("ENRICHED POPULATION COST-EFFECTIVENESS ANALYSIS\n")
cat("Biomarker-positive experimental vs biomarker-positive control\n")
cat(rep("=", 80), "\n", sep = "")

enriched_results <- run_enriched_analysis(verbose = TRUE)
enriched_comparison <- enriched_results$comparison
